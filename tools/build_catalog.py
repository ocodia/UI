#!/usr/bin/env python3
"""Generate catalogue views, component references and trusted example pages (stdlib only)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = {'native': 'Native recipe', 'foundation': 'Foundation', 'planned': 'Planned'}


def generate():
    data = json.loads((ROOT / 'docs/components.json').read_text())
    entries = data['components']
    ids = [item['id'] for item in entries + data['uiComponents']]
    if len(ids) != len(set(ids)):
        raise ValueError('Component IDs must be unique.')
    for item in entries:
        if item['status'] not in LABELS or item['phase'] not in range(1, 6):
            raise ValueError(f'Invalid status/phase: {item["id"]}')
        for key in ['name', 'category', 'reference', 'ui', 'contract', 'acceptance']:
            if not item.get(key):
                raise ValueError(f'{item["id"]} is missing {key}')
        specification = item.get('specification')
        if specification and (not specification.startswith('docs/specs/') or not specification.endswith('.md') or '..' in Path(specification).parts or not (ROOT/specification).is_file()):
            raise ValueError(f'Invalid specification source: {item["id"]}')
    md = ['<!-- Generated by tools/build_catalog.py; edit components.json. -->', '# Component catalogue', '',
          f'Reviewed {data["reviewed"]}: [Web Awesome reference catalogue]({data["reference"]}). '
          f'{len(entries)} reference entries and {len(data["uiComponents"])} existing UI primitives.', '',
          data['description'], '',
          'Delivery phases and the stable-release gate are in [ROADMAP.md](../ROADMAP.md). '
          'Examples are minimal structures, not complete applications. Native/foundation entries still need the listed release evidence. '
          'Proposed widgets have contracts instead of pretend live demos.', '', '## Existing UI primitives', '']
    for item in data['uiComponents']:
        md += [f'### {item["id"]}', '', f'**Foundation · {item["mode"]}.** {item["contract"]}', '',
               '```html', item['example'], '```', '', '[Current API](reference.md)', '']
    for category in dict.fromkeys(item['category'] for item in entries):
        md += [f'## {category}', '']
        for item in [entry for entry in entries if entry['category'] == category]:
            label = LABELS[item['status']]
            md += [f'### {item["name"]}', '', f'**{label} · Phase {item["phase"]}.** UI route: `{item["ui"]}`.', '',
                   item['contract'], '', f'**Acceptance work:** {item["acceptance"]}', '']
            if item.get('example'):
                md += ['```html', item['example'], '```', '']
            if item.get('exampleNote'):
                md += [item['exampleNote'], '']
            if item.get('specification'):
                md += [f'[Component specification]({item["specification"].removeprefix("docs/")})', '']
            md += [f'[Reference component]({item["reference"]}) · [Specification template](component-template.md)', '']
    from site_content import catalogue_pages
    recipes = json.loads((ROOT / 'docs/recipes.json').read_text())
    return {'docs/components.md':'\n'.join(md).rstrip()+'\n', **catalogue_pages(data, recipes)}



def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail if committed generated files differ.')
    args=parser.parse_args()
    stale=[]
    for filename, content in generate().items():
        path=ROOT/filename
        if args.check:
            if not path.exists() or path.read_text()!=content: stale.append(filename)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit('Stale catalogue output: '+', '.join(stale)+'. Run python3 tools/build_catalog.py')
    print('Catalogue views are current.' if args.check else 'Generated catalogue, component references and example previews.')

if __name__=='__main__': main()
