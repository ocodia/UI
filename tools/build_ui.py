#!/usr/bin/env python3
"""Build the optional combined classic-script entry point; no runtime loader."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['js/components.js', 'js/popup.js', 'js/enhance.js']

def generate():
    return '// Generated by tools/build_ui.py; edit the source files instead.\n' + '\n'.join(f'\n// Source: {name}\n'+(ROOT/name).read_text().rstrip()+'\n' for name in SOURCES)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'js/ui.js'
    content = generate()
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('Stale js/ui.js; run python3 tools/build_ui.py')
        print('Combined UI entry point is current.')
    else:
        path.write_text(content)
        print('Generated js/ui.js from components, geometry and enhancement sources.')

if __name__ == '__main__': main()
