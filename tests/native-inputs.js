// Real native controls and local application integration, not simulated widget APIs.
async function runNativeInputChecks(win) {
  const doc = win.document;
  const editor = doc.querySelector('#visit-editor');
  const form = editor.form;
  const summary = editor.querySelector('ui-error-summary');
  const submitter = doc.querySelector('#visit-submit');
  const result = doc.querySelector('#visit-result');
  const status = doc.querySelector('#visit-status');
  const date = form.elements.date;
  const time = form.elements.time;
  const files = form.elements.documents;
  const boxes = [...form.querySelectorAll('[name="format"]')];
  const radios = [...form.querySelectorAll('[name="kind"]')];
  const passed = [];
  const check = (condition, message) => { assert(condition, message); passed.push(message); };
  const settle = () => new Promise(resolve => win.setTimeout(resolve, 0));
  const submit = () => form.requestSubmit(submitter);
  const changeFiles = (selected) => {
    const transfer = new win.DataTransfer();
    selected.forEach(file => transfer.items.add(file));
    files.files = transfer.files;
    files.dispatchEvent(new win.Event('change', { bubbles: true }));
  };
  const entries = () => [...doc.querySelectorAll('#visit-values dt')].map(term => [term.textContent, term.nextElementSibling.textContent]);
  check(!submitter.hidden && doc.querySelector('#visit-fallback').hidden && form.enctype === 'multipart/form-data', 'Native-value recipe exposes inspection only after installing local behavior.');
  submit();
  check(summary.querySelectorAll('li').length === 4 && doc.activeElement === summary && doc.title.startsWith('Error: '), 'Empty date, time, radio and checkbox questions yield four linked errors and summary focus.');
  check(date.getAttribute('aria-describedby').includes('visit-when-hint') && date.getAttribute('aria-describedby').includes('visit-date-hint') && time.getAttribute('aria-describedby').includes('visit-time-hint'), 'Date/time errors preserve both contextual and individual hints.');
  check(date.closest('ui-field').querySelector('ui-error') !== time.closest('ui-field').querySelector('ui-error'), 'Distinct date/time answers retain separate inline errors.');
  check(radios.every(radio => radio.getAttribute('aria-invalid') === 'true') && doc.querySelector('#visit-kind').getAttribute('aria-describedby').includes('visit-kind-error'), 'The required radio question has one shared fieldset error and invalid eligible members.');
  check(boxes[0].getAttribute('aria-invalid') === 'true' && !boxes[1].hasAttribute('aria-invalid') && doc.querySelector('#visit-formats').getAttribute('aria-describedby').includes('visit-formats-error'), 'Checkbox minimum-count feedback describes the group and marks its representative.');
  summary.querySelector('a[href="#visit-html"]').click();
  check(doc.activeElement === boxes[0] && !boxes[0].checked, 'A checkbox summary link focuses its representative without choosing an answer.');
  date.value = '2026-10-20'; time.value = '09:15'; radios[1].checked = true; boxes[1].checked = true;
  submit();
  check(summary.hidden && !doc.title.startsWith('Error: ') && !result.hidden && status.textContent.includes('Nothing was sent'), 'Correcting all questions inspects values locally and clears error/title state.');
  check(date.getAttribute('aria-describedby') === 'visit-when-hint visit-date-hint' && doc.querySelector('#visit-kind').getAttribute('aria-describedby') === 'visit-kind-hint' && doc.querySelector('#visit-formats').getAttribute('aria-describedby') === 'visit-formats-hint', 'Recovery removes error associations while preserving all authored hints.');
  const data = new win.FormData(form, submitter);
  check(data.get('date') === '2026-10-20' && data.get('time') === '09:15' && data.get('kind') === 'independent' && data.get('intent') === 'inspect', 'Native FormData retains calendar date, local time, radio value and successful submitter.');
  check(data.get('venue') === 'FIELD-01' && !data.has('staff'), 'Read-only data serializes while a disabled control is omitted.');
  check(data.get('documents') instanceof win.File && data.get('documents').name === '' && entries().some(([key, value]) => key === 'documents' && value.includes('empty File')), 'Optional empty file selection is shown as its native empty File entry.');
  boxes[0].checked = true; submit();
  check(new win.FormData(form).getAll('format').join() === 'html,text' && entries().filter(([key]) => key === 'format').map(([,value]) => value).join() === 'html,text', 'Repeated checked names remain repeated entries in native data and the inspector.');
  const level = form.elements.level;
  level.stepUp(); level.dispatchEvent(new win.Event('input', { bubbles: true }));
  check(level.value === '55' && doc.querySelector('#visit-level-value').value === '55%' && result.hidden && status.textContent === '', 'Native range stepping updates its visible value and invalidates old inspection results.');
  submit();
  check(new win.FormData(form).get('level') === '55', 'Native range value serializes as a numeric string.');
  date.value = '2025-12-31'; submit();
  check(date.validity.rangeUnderflow && summary.textContent.includes('1 January 2026') && date.getAttribute('aria-invalid') === 'true', 'A date below the fixed window receives actionable bound feedback.');
  date.value = '2028-01-01'; submit();
  check(date.validity.rangeOverflow && !summary.hidden, 'A date above the fixed window remains invalid.');
  date.value = '2026-10-20'; time.value = '08:45'; submit();
  check(time.validity.rangeUnderflow && summary.textContent.includes('15-minute intervals'), 'A time before opening receives actionable interval guidance.');
  time.value = '17:15'; submit();
  check(time.validity.rangeOverflow && !summary.hidden, 'A time after closing remains invalid.');
  time.value = '09:10'; submit();
  check(time.validity.stepMismatch && summary.textContent.includes('15-minute intervals'), 'A time between native 900-second steps fails validation.');
  time.setCustomValidity('This time is reserved'); submit();
  check(summary.textContent.includes('This time is reserved'), 'Explicit custom validity survives simultaneous native time constraints.');
  time.setCustomValidity('');
  time.value = '09:15';
  const large = new win.File([new Uint8Array(1048577)], 'oversize.txt', { type: 'text/plain' });
  changeFiles([large]); submit();
  check(summary.querySelector('a[href="#visit-files"]') && summary.textContent.includes('1 MiB') && files.files[0].name === 'oversize.txt', 'An oversized file produces linked feedback without clearing native selection.');
  const small = index => new win.File(['notes'], `notes-${index}.txt`, { type: 'text/plain' });
  changeFiles([small(1), small(2), small(3), small(4)]); submit();
  check(summary.textContent.includes('no more than 3'), 'More than three selected files fails the application count rule.');
  const boundary = new win.File([new Uint8Array(1048576)], 'boundary.txt', { type: 'text/plain' });
  const escaped = new win.File(['notes'], '<img src=x onerror=alert(1)>.txt', { type: 'text/plain' });
  const empty = new win.File([], 'empty.txt', { type: 'text/plain' });
  changeFiles([boundary, escaped, empty]); submit();
  check(summary.hidden && new win.FormData(form).getAll('documents').length === 3 && entries().filter(([key]) => key === 'documents').length === 3, 'Exactly three files including a 1 MiB file pass and preserve repeated native File entries.');
  check(doc.querySelector('#visit-values').textContent.includes(escaped.name) && !doc.querySelector('#visit-values img'), 'File names render as text rather than executable markup.');
  check(entries().some(([key, value]) => key === 'documents' && value.startsWith('empty.txt') && value.includes('0 bytes')), 'A selected zero-byte file remains distinct from an empty selection.');
  form.addEventListener('reset', event => event.preventDefault(), { once: true });
  form.reset(); await settle();
  check(files.files.length === 3 && date.value === '2026-10-20' && !result.hidden && level.value === '55', 'Cancelled reset preserves selected files, answers and the inspected result.');
  form.reset(); await settle();
  check(date.value === '' && time.value === '' && radios.every(radio => !radio.checked) && boxes.every(box => !box.checked) && files.files.length === 0, 'Native reset clears date/time, choice answers and file selection.');
  check(level.value === '50' && doc.querySelector('#visit-level-value').value === '50%' && result.hidden && status.textContent === '' && summary.hidden, 'Reset restores the range default and clears application/managed feedback.');
  submit(); form.addEventListener('reset', event => event.preventDefault(), { once: true }); form.reset(); await settle();
  check(!summary.hidden && doc.title.startsWith('Error: '), 'Cancelled reset also preserves grouped errors and the error title.');
  form.reset(); await settle();
  check(summary.hidden && !doc.title.startsWith('Error: '), 'Uncancelled reset clears grouped errors and restores the title.');
  date.value = '2026-10-20'; time.value = '09:15'; radios[0].checked = true; boxes[0].checked = true;
  changeFiles([new win.File(['notes'], `${'long-filename-'.repeat(18)}.txt`, { type: 'text/plain' })]);
  submit();
  const frame = win.frameElement;
  const priorWidth = frame.style.inlineSize;
  frame.style.inlineSize = '320px';
  doc.documentElement.style.fontSize = '200%';
  doc.documentElement.style.lineHeight = '1.5';
  doc.documentElement.style.letterSpacing = '.12em';
  doc.documentElement.style.wordSpacing = '.16em';
  try {
    for (const dir of ['ltr', 'rtl']) {
      doc.documentElement.dir = dir;
      await new Promise(resolve => win.setTimeout(resolve, 60));
      check(doc.documentElement.scrollWidth <= doc.documentElement.clientWidth + 1, `Enhanced native inputs and long file metadata reflow at 320px in ${dir} with doubled text and expanded spacing.`);
    }
  } finally {
    frame.style.inlineSize = priorWidth;
    doc.documentElement.removeAttribute('style');
    doc.documentElement.dir = 'ltr';
  }
  return passed;
}
