// Server-rendered state must become managed without a second render or focus theft.
async function runServerErrorChecks(fixture) {
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); passed.push(message); };
  const settle = async () => { await Promise.resolve(); await Promise.resolve(); };
  const title = document.title;
  try {
    fixture.innerHTML = '<button type="button">Keep focus here</button>';
    const keeper = fixture.querySelector('button');
    keeper.focus();
    document.title = `Error: ${title}`;
    const host = document.createElement('ui-form');
    host.innerHTML = `<ui-error-summary><h2>There is a problem</h2><ul><li><a href="#server-name">This name is already in use</a></li></ul></ui-error-summary>
      <form><ui-field><label for="server-name">Project name</label><ui-hint id="server-hint">Use a recognisable name.</ui-hint><ui-error id="server-error">Error: This name is already in use</ui-error><input id="server-name" name="project" value="Taken" required aria-invalid="true" aria-describedby="server-hint server-error"></ui-field><button>Save</button></form>`;
    const originalLink = host.querySelector('a');
    fixture.append(host);
    await settle();
    const form = host.form;
    const name = form.elements.project;
    const error = host.querySelector('ui-error');
    const summary = host.querySelector('ui-error-summary');
    check(name.value === 'Taken' && !error.hidden && summary.querySelector('a') === originalLink, 'Initial server answers, inline messages and summary links survive enhancement.');
    check(document.activeElement === keeper, 'Adopting server errors does not steal focus.');
    host.refresh();
    host.refresh();
    check(summary.querySelectorAll('li').length === 1 && document.title === `Error: ${title}`, 'Repeated refresh neither duplicates server errors nor the title prefix.');
    host.clear();
    check(error.hidden && summary.hidden && !name.hasAttribute('aria-invalid') && name.getAttribute('aria-describedby') === 'server-hint', 'Clearing adopted errors removes only their associations and preserves hints.');
    check(document.title === title && name.value === 'Taken', 'Clearing an adopted error restores the server-prefixed title and preserves answers.');
    name.value = '';
    host.validate({ focus: false });
    check(!summary.querySelector('a').textContent.includes('already in use'), 'A server domain error is not reused as the required-field message.');
    name.setCustomValidity('Saisissez le nom du projet');
    host.validate({ focus: false });
    check(summary.querySelector('a').textContent === 'Saisissez le nom du projet', 'Explicit custom validity wins when a required field is also empty.');
    name.setCustomValidity('');
    name.value = 'Corrected name';
    let submitted = false;
    form.addEventListener('submit', (event) => { event.preventDefault(); submitted = true; });
    form.requestSubmit();
    check(submitted && error.hidden && summary.hidden && name.getAttribute('aria-describedby') === 'server-hint', 'A corrected native submission clears adopted errors without removing hints.');
    fixture.replaceChildren();
    const external = document.createElement('input');
    external.id = 'server-external';
    external.name = 'external';
    external.value = 'External answer';
    external.setAttribute('form', 'server-external-form');
    external.setAttribute('aria-invalid', 'true');
    external.setAttribute('aria-describedby', 'server-external-hint server-external-error');
    fixture.innerHTML = '<p id="server-external-hint">External hint.</p><ui-error id="server-external-error">Error: Check this external answer</ui-error>';
    fixture.append(external);
    const externalHost = document.createElement('ui-form');
    externalHost.innerHTML = '<form id="server-external-form"><button>Save</button></form>';
    fixture.append(externalHost);
    await settle();
    check(externalHost.querySelector('ui-error-summary a')?.hash === '#server-external', 'External form-associated server errors populate a missing summary.');
    externalHost.clear();
    check(fixture.querySelector('#server-external-error').hidden && external.getAttribute('aria-describedby') === 'server-external-hint', 'External authored errors are cleared through their explicit associations.');
    fixture.replaceChildren();
    const radios = document.createElement('ui-form');
    radios.innerHTML = `<form><fieldset aria-describedby="server-radio-error"><legend>Contact route</legend><ui-error id="server-radio-error">Error: Select a contact route</ui-error><label><input type="radio" name="route" value="email" aria-invalid="true" aria-describedby="server-radio-error" required>Email</label><label><input type="radio" name="route" value="phone" aria-invalid="true">Phone</label></fieldset></form>`;
    fixture.append(radios);
    await settle();
    check(radios.querySelectorAll('ui-error-summary li').length === 1, 'Server radio groups produce one summary error even with multiple invalid members.');
    radios.clear();
    check([...radios.form.elements].filter((control) => control.type === 'radio').every((control) => !control.hasAttribute('aria-invalid') && !control.hasAttribute('aria-describedby')) && !radios.querySelector('fieldset').hasAttribute('aria-describedby'), 'Clearing server radio errors cleans both control and group associations.');
    fixture.replaceChildren();
    const resetHost = document.createElement('ui-form');
    resetHost.innerHTML = '<form><ui-field><label for="server-reset">Reference</label><ui-error id="server-reset-error">Error: Check the reference</ui-error><input id="server-reset" value="Original answer" aria-invalid="true" aria-describedby="server-reset-error"></ui-field></form>';
    fixture.append(resetHost);
    await settle();
    resetHost.form.addEventListener('reset', (event) => event.preventDefault(), { once: true });
    resetHost.form.reset();
    await settle();
    check(!resetHost.querySelector('ui-error').hidden, 'Cancelled native reset preserves adopted server errors.');
    resetHost.form.querySelector('input').value = 'Edited answer';
    resetHost.form.reset();
    await settle();
    check(resetHost.querySelector('ui-error').hidden && resetHost.form.querySelector('input').value === 'Original answer', 'Native reset clears server errors and restores default answers.');
    fixture.replaceChildren();
    const incomplete = document.createElement('ui-form');
    incomplete.innerHTML = '<ui-error-summary hidden><ul></ul></ui-error-summary><form><label>Answer<input name="answer" value="Complete" required></label><button>Save</button></form>';
    fixture.append(incomplete);
    await settle();
    let fallbackSubmitted = false;
    incomplete.form.addEventListener('submit', (event) => { event.preventDefault(); fallbackSubmitted = true; });
    incomplete.form.requestSubmit();
    check(!incomplete.form.noValidate && fallbackSubmitted, 'An incomplete summary leaves native valid submissions usable.');
    incomplete.querySelector('ui-error-summary').prepend(document.createElement('h2'));
    incomplete.querySelector('h2').textContent = 'There is a problem';
    await settle();
    check(incomplete.form.noValidate && incomplete.validate({ focus: false }), 'Completing summary markup enables enhancement without reconnecting the form.');
    return passed;
  } finally {
    fixture.replaceChildren();
    document.title = title;
  }
}
