// Native form ownership, shared question feedback and application-supplied language.
async function runFormIntegrationChecks(fixture) {
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); passed.push(message); };
  const settle = () => new Promise((resolve) => setTimeout(resolve, 0));
  const title = document.title;
  try {
    fixture.innerHTML = `<ui-form id="owner-a"><form id="owned-a"><button name="intent" value="save">Save A</button></form></ui-form>
      <ui-form id="owner-b"><form id="owned-b"><button>Save B</button></form></ui-form>
      <p id="authored-detail">Keep this description.</p><div id="external-fields"></div>`;
    await settle();
    const a = fixture.querySelector('#owner-a');
    const b = fixture.querySelector('#owner-b');
    const field = document.createElement('ui-field');
    field.innerHTML = '<label for="owned-answer">External answer</label><ui-hint id="owned-hint">External hint.</ui-hint><input id="owned-answer" name="answer" form="owned-a" required aria-describedby="authored-detail">';
    fixture.querySelector('#external-fields').append(field);
    await settle();
    const input = field.querySelector('input');
    check(input.getAttribute('aria-describedby') === 'authored-detail owned-hint', 'Late external controls discover their hints without an explicit refresh.');
    let submits = 0;
    let submitter;
    a.form.addEventListener('submit', (event) => { event.preventDefault(); submits++; submitter = event.submitter; });
    a.form.requestSubmit(a.form.querySelector('button'));
    check(submits === 0 && a.querySelector('ui-error-summary a').hash === '#owned-answer', 'An externally associated required field blocks submission and gets a real summary link.');
    input.value = 'A preserved answer';
    const externalSubmit = document.createElement('button');
    externalSubmit.setAttribute('form', 'owned-a');
    externalSubmit.name = 'intent'; externalSubmit.value = 'external'; externalSubmit.textContent = 'External save';
    fixture.append(externalSubmit);
    externalSubmit.click();
    check(submits === 1 && submitter === externalSubmit && new FormData(a.form, submitter).get('intent') === 'external', 'External submit buttons retain successful submitter name/value and native events.');
    input.value = '';
    a.validate({ focus: false });
    input.setAttribute('form', 'owned-b');
    await settle();
    check(a.querySelector('ui-error-summary').hidden && !input.hasAttribute('aria-invalid') && document.title === title, 'Changing an external form owner clears the former owner’s error and title automatically.');
    check(!b.validate({ focus: false }) && b.querySelector('ui-error-summary a').hash === '#owned-answer', 'The new form validates the reassigned control.');
    a.clear();
    check(input.getAttribute('aria-invalid') === 'true' && !field.querySelector('ui-error').hidden, 'Clearing the former owner cannot erase the new owner’s error.');
    input.id = 'renamed-answer';
    await settle();
    check(b.querySelector('ui-error-summary a').hash === '#renamed-answer', 'Changing a managed external control ID updates the summary destination.');
    const externalError = field.querySelector('ui-error');
    const oldErrorId = externalError.id;
    externalError.id = 'renamed-answer-error';
    await settle();
    check(input.getAttribute('aria-describedby').includes('renamed-answer-error') && !input.getAttribute('aria-describedby').split(' ').includes(oldErrorId), 'Changing a managed error ID replaces its owned association without stale IDs.');
    input.readOnly = true;
    await settle();
    check(b.querySelector('ui-error-summary').hidden && !input.hasAttribute('aria-invalid'), 'Read-only external controls relinquish stale managed errors.');
    input.readOnly = false;
    b.validate({ focus: false });
    input.disabled = true;
    await settle();
    check(b.querySelector('ui-error-summary').hidden && !input.hasAttribute('aria-invalid'), 'Disabling an invalid external field removes its stale summary state.');
    input.disabled = false;
    b.validate({ focus: false });
    field.remove();
    await settle();
    check(b.querySelector('ui-error-summary').hidden && input.getAttribute('aria-describedby') === 'authored-detail', 'Removing an external field clears stale errors and only enhancement-added hints.');
    b.form.append(field);
    input.removeAttribute('form');
    await settle();
    check(input.form === b.form && input.getAttribute('aria-describedby') === 'authored-detail owned-hint', 'Moving a field into a form preserves authored descriptions and rediscovers its hint.');
    field.querySelector('ui-hint').remove();
    await settle();
    check(input.getAttribute('aria-describedby') === 'authored-detail', 'Removing a hint removes its enhancement-owned association.');
    input.value = 'Kept';
    b.remove();
    check(input.getAttribute('aria-describedby') === 'authored-detail' && !b.querySelector('form').noValidate, 'Disconnect restores native validation without losing authored descriptions.');
    fixture.append(b);
    await settle();
    const renamed = a.form;
    input.setAttribute('form', 'owned-a');
    renamed.id = 'renamed-a';
    await settle();
    check(input.form === null && a.validate({ focus: false }), 'Renaming a form follows native association rules rather than cached ownership.');
    renamed.id = 'owned-a';
    await settle();
    check(input.form === a.form && new FormData(a.form).get('answer') === 'Kept', 'Restoring the form ID restores native value serialization.');

    fixture.innerHTML = `<ui-form><form><fieldset aria-describedby="route-hint"><legend>Contact route</legend><ui-hint id="route-hint">Choose one.</ui-hint><ui-error hidden>Error: Select a contact route</ui-error><label><input id="route-email" type="radio" name="route" value="email" required>Email</label><label><input id="route-phone" type="radio" name="route" value="phone">Phone</label></fieldset><button>Save</button></form></ui-form>`;
    await settle();
    const radioHost = fixture.querySelector('ui-form');
    const group = radioHost.querySelector('fieldset');
    const radios = [...group.querySelectorAll('input')];
    radioHost.validate({ focus: false });
    check(radioHost.querySelectorAll('ui-error-summary li').length === 1 && radios.every((radio) => radio.getAttribute('aria-invalid') === 'true'), 'A native radio question has one summary error and marks every eligible member invalid.');
    check(group.getAttribute('aria-describedby').includes('route-hint') && group.getAttribute('aria-describedby').includes(group.querySelector('ui-error').id), 'Shared radio feedback augments the fieldset hint.');
    radioHost.showErrors(radios.map((control) => ({ control, message: 'Choose a contact route' })), { focus: false });
    check(radioHost.querySelectorAll('ui-error-summary li').length === 1, 'Application errors for members of one native radio group collapse to one question.');
    radios[1].remove();
    await settle();
    check(radioHost.querySelector('ui-error-summary a').hash === '#route-email', 'Removing the radio summary representative retains the error on a surviving group member.');
    const nextGroup = document.createElement('fieldset');
    nextGroup.innerHTML = '<legend>Moved contact route</legend>';
    radioHost.form.append(nextGroup);
    nextGroup.append(radios[0]);
    await settle();
    check(!group.getAttribute('aria-describedby').includes(group.querySelector('ui-error').id) && nextGroup.getAttribute('aria-describedby').includes(nextGroup.querySelector('ui-error').id), 'Moving a radio group replaces its old fieldset error association.');
    nextGroup.disabled = true;
    await settle();
    check(radioHost.querySelector('ui-error-summary').hidden && !radios[0].hasAttribute('aria-invalid'), 'A disabled fieldset clears stale errors for its descendants.');
    nextGroup.disabled = false;
    radioHost.validate({ focus: false });
    radios[0].checked = true;
    check(radioHost.validate({ focus: false }) && group.getAttribute('aria-describedby') === 'route-hint' && !radios[0].hasAttribute('aria-invalid'), 'Correcting a radio question clears group feedback and retains its hint.');

    fixture.innerHTML = `<ui-form><form><fieldset aria-describedby="topics-hint"><legend>Updates</legend><ui-hint id="topics-hint">Choose at least one.</ui-hint><ui-error hidden>Error: Select at least one update</ui-error><label><input type="checkbox" name="topics" value="news">News</label><label><input type="checkbox" name="topics" value="events">Events</label></fieldset></form></ui-form>`;
    await settle();
    const checkHost = fixture.querySelector('ui-form');
    const boxes = [...checkHost.form.querySelectorAll('input')];
    checkHost.validator = (form) => new FormData(form).getAll('topics').length ? [] : [{ control: boxes[0], message: 'Select at least one update' }];
    check(!checkHost.validate({ focus: false }) && checkHost.querySelector('fieldset').getAttribute('aria-describedby').includes(checkHost.querySelector('ui-error').id), 'Checkbox questions use an explicit group error and application-owned at-least-one rule.');
    boxes[1].checked = true;
    check(checkHost.validate({ focus: false }) && checkHost.querySelector('fieldset').getAttribute('aria-describedby') === 'topics-hint' && new FormData(checkHost.form).getAll('topics').join() === 'events', 'Checkbox correction preserves shared hints and repeated native form values.');

    fixture.innerHTML = `<ui-form lang="fr" error-prefix="Erreur : " error-title-prefix="Erreur :"><ui-error-summary hidden><h2>Il y a un problème</h2><ul></ul></ui-error-summary><form><ui-field><label for="french-name">Nom du projet</label><ui-error hidden>Erreur : Saisissez le nom du projet</ui-error><input id="french-name" name="project" required maxlength="8"></ui-field></form></ui-form>`;
    await settle();
    const french = fixture.querySelector('ui-form');
    const name = french.form.elements.project;
    french.validate({ focus: false });
    check(french.querySelector('ui-error-summary a').textContent === 'Saisissez le nom du projet' && french.querySelector('ui-error').textContent === 'Erreur : Saisissez le nom du projet', 'Authored localized required messages use the configured inline prefix once.');
    check(document.title === `Erreur : ${title}`, 'The error title uses the application’s localized prefix.');
    name.value = 'Trop de caractères';
    let context;
    french.message = (control, detail) => { context = detail; return `${detail.label} : ${control.maxLength} caractères maximum`; };
    french.validate({ focus: false });
    check(context.reason === 'tooLong' && context.label === 'Nom du projet' && french.querySelector('ui-error-summary a').textContent === 'Nom du projet : 8 caractères maximum', 'A synchronous message callback can translate generated constraint messages using their reason and label.');
    french.message = () => Promise.resolve('Bad async message');
    let rejected = false;
    try { french.validate({ focus: false }); } catch (error) { rejected = error instanceof TypeError; }
    check(rejected && !french.querySelector('ui-error-summary').hidden, 'Async message callbacks are rejected without erasing existing feedback.');
    french.message = null;
    french.clear();
    check(document.title === title && french.querySelector('ui-error').hidden, 'Clearing localized feedback restores the original title.');
    document.title = `Erreur : ${title}`;
    name.value = 'Pris'; name.setAttribute('aria-invalid', 'true');
    const localized = french.querySelector('ui-error');
    localized.hidden = false; localized.textContent = 'Erreur : Ce nom est déjà utilisé';
    name.setAttribute('aria-describedby', localized.id);
    french.refresh();
    check(french.querySelector('ui-error-summary a').textContent === 'Ce nom est déjà utilisé', 'Localized server errors are adopted without leaking their prefix into summary links.');
    french.clear();
    check(document.title === title, 'A localized server title prefix is removed after the last error clears.');
    return passed;
  } finally {
    fixture.replaceChildren();
    document.title = title;
  }
}

async function runAsyncFormChecks(win) {
  const doc = win.document;
  const editor = doc.querySelector('#delivery-editor');
  const form = editor.form;
  const status = doc.querySelector('#delivery-status');
  const failure = doc.querySelector('#delivery-failure');
  const cancel = doc.querySelector('#delivery-cancel');
  const submitter = [...form.elements].find((control) => control.type === 'submit');
  const email = form.elements.email;
  const outcome = doc.querySelector('#delivery-outcome');
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); passed.push(message); };
  const wait = () => new Promise((resolve) => win.setTimeout(resolve, 850));
  const settle = () => new Promise((resolve) => win.setTimeout(resolve, 0));
  const edit = (control, value) => { control.value = value; control.dispatchEvent(new win.Event('input', { bubbles: true })); };
  check(!doc.querySelector('#delivery-enhanced').hidden && email.form === form && email.closest('form') === null, 'Integration recipe enhances real external fields and submitters.');
  const original = email.value;
  form.requestSubmit(submitter);
  check(form.getAttribute('aria-busy') === 'true' && !cancel.hidden && !email.disabled && !submitter.disabled, 'Async application feedback exposes pending state while preserving editable fields and successful submitters.');
  form.requestSubmit(submitter);
  await wait();
  check(status.textContent.includes(`Updates requested for ${original}`) && !form.hasAttribute('aria-busy') && cancel.hidden, 'A valid request completes once with a persistent success message and no navigation.');
  outcome.value = 'field';
  form.requestSubmit(submitter);
  await wait();
  check(!editor.querySelector('ui-error-summary').hidden && doc.activeElement === editor.querySelector('ui-error-summary') && email.value === original, 'Async field rejection uses UI summary focus and preserves the external answer.');
  editor.querySelector('ui-error-summary a').click();
  check(doc.activeElement === email && email.getAttribute('aria-describedby').includes('delivery-email-hint'), 'Async error links focus external fields and preserve hints.');
  edit(email, 'replacement@example.com');
  outcome.value = 'failure';
  form.requestSubmit(submitter);
  await wait();
  check(!failure.hidden && status.textContent.includes('Request failed') && email.value === 'replacement@example.com' && editor.querySelector('ui-error-summary').hidden, 'Service failures have persistent task feedback without fabricating invalid field errors.');
  outcome.value = 'success';
  form.requestSubmit(submitter);
  await wait();
  check(failure.hidden && status.textContent.includes('Updates requested'), 'A failed request can be retried successfully with the preserved answers.');
  outcome.value = 'field';
  form.requestSubmit(submitter);
  edit(email, 'latest@example.com');
  await wait();
  check(!form.hasAttribute('aria-busy') && status.textContent.includes('Answers changed') && editor.querySelector('ui-error-summary').hidden, 'Editing an external answer cancels and invalidates an older field-error response.');
  form.requestSubmit(submitter);
  cancel.click();
  await wait();
  check(status.textContent.includes('Request cancelled') && doc.activeElement === submitter && !form.hasAttribute('aria-busy'), 'Explicit cancellation returns focus to the submitter and prevents late feedback.');
  form.requestSubmit(submitter);
  form.addEventListener('reset', (event) => event.preventDefault(), { once: true });
  form.reset();
  await settle();
  check(form.getAttribute('aria-busy') === 'true' && email.value === 'latest@example.com', 'A cancelled reset leaves the pending operation and answers intact.');
  form.reset();
  await wait();
  check(email.value === original && status.textContent === 'Answers reset.' && editor.querySelector('ui-error-summary').hidden && !form.hasAttribute('aria-busy'), 'Native reset restores external defaults and invalidates an older response.');
  const boxes = [...form.elements.updates];
  boxes.forEach((box) => { box.checked = false; });
  form.requestSubmit(submitter);
  check(!form.hasAttribute('aria-busy') && editor.querySelector('ui-error-summary').textContent.includes('Select at least one update'), 'Synchronous checkbox-group validation stops the async transport before pending state.');
  boxes[1].checked = true;
  outcome.value = 'field';
  form.requestSubmit(submitter);
  const position = editor.nextSibling;
  const parent = editor.parentNode;
  editor.remove();
  await wait();
  check(!form.hasAttribute('aria-busy') && !status.textContent.includes('Use a different email') && !email.hasAttribute('aria-invalid'), 'Removing the editor prevents a pending response from rendering errors or moving focus.');
  parent.insertBefore(editor, position);
  await settle();
  const french = doc.querySelector('#french-editor');
  french.form.requestSubmit();
  check(french.querySelector('ui-error-summary a').textContent === 'Saisissez le nom du projet' && doc.title.startsWith('Erreur : '), 'The French example renders translated required feedback and title.');
  french.form.elements.project.value = 'Guide';
  french.form.requestSubmit();
  check(french.querySelector('ui-error-summary').hidden && doc.querySelector('#french-result').textContent.includes('Aucune donnée'), 'The French example recovers with native submission and localized success text.');
  return passed;
}
